 assert shutil.which("ffmpeg"), "ffmpeg é necessário para decodificar a voz natural aprovada na compilação"
 with TemporaryDirectory() as directory:
  compressed=Path(directory)/"approved.opus"
  compressed.write_bytes(decoded)
  normal=target/"order-merchant-voice-1.wav"
  subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-y","-i",str(compressed),"-ar","24000","-ac","1","-c:a","pcm_s16le",str(normal)],check=True,timeout=50)
 with wave.open(str(normal),"rb") as wav:
  assert (wav.getnchannels(),wav.getsampwidth(),wav.getframerate())==(1,2,24000)
  n=wav.getnframes()
  assert 24000*2<=n<=24000*4, "Duração inesperada da voz"
  samples=wav.readframes(n)
  assert max(abs(int.from_bytes(samples[i:i+2],"little",signed=True)) for i in range(0,len(samples),2))>1500
 for level,gain in [(2,1.5),(3,2.0)]:
  data=array("h")
  data.frombytes(samples)
  if sys.byteorder!="little":data.byteswap()
  out=array("h")
  for item in data:
   value=math.tanh((item/32768.0)*gain)*32760.0
   out.append(max(-32767,min(32767,round(value))))
  if sys.byteorder!="little":out.byteswap()
  with wave.open(str(target/f"order-merchant-voice-{level}.wav"),"wb") as wav:
   wav.setparams((1,2,24000,0,"NONE","not compressed"))
   wav.writeframes(out.tobytes())

