"""Bundle exactly one approved merchant voice and five native Windows bells.

The source voice is a compact Opus encoding of the provided, approved
recording. At build time ffmpeg decodes it into fixed PCM16 WAV files
embedded by Rust. Playback requires no internet, download, or import.
"""
