rate=24000
for name,notes in bells.items():
 for level,volume in [(1,.42),(2,.76),(3,.98)]:
  pcm=array("h")
  for i in range(round(rate*2.40)):
   t=i/rate;signal=0.0
   for start,freq,strength in notes:
    elapsed=t-start
    if elapsed<0 or elapsed>1.05:continue
    envelope=min(1,elapsed/.005)*math.exp(-4.2*elapsed)
    harmonics=math.sin(2*math.pi*freq*elapsed)+.32*math.sin(4*math.pi*freq*elapsed)+.14*math.sin(6*math.pi*freq*elapsed)
    signal+=strength*envelope*harmonics
   sample=math.tanh(3.8*signal)*volume*min(1,max(0,(2.4-t)/.10))
   pcm.append(max(-32767,min(32767,round(sample*32767))))
  if sys.byteorder!="little":pcm.byteswap()
  with wave.open(str(target/f"order-bell-{name}-{level}.wav"),"wb") as wav:
   wav.setparams((1,2,rate,0,"NONE","not compressed"))
   wav.writeframes(pcm.tobytes())
